// sep-origin/alpha2-desktop/apps/desktop/src/preload-welcome.ts
var prefix = "--dsh-welcome-locale=";
var locale = process.argv.find((argument) => argument.startsWith(prefix))?.slice(prefix.length);
if (locale === void 0) throw new Error("desktop welcome: missing window locale");
var api = {
  ...resolveDesktopLocale(locale),
  analytics: async (eventName, attributes) => {
    if (await api.analyticsEnabled()) await import_electron.ipcRenderer.invoke(WELCOME_IPC.analytics, eventName, attributes);
  },
  analyticsEnabled: () => import_electron.ipcRenderer.invoke(WELCOME_IPC.analyticsEnabled),
  takeNotice: () => import_electron.ipcRenderer.invoke(WELCOME_IPC.takeNotice),
  startSignIn: () => import_electron.ipcRenderer.invoke(WELCOME_IPC.start),
  cancelSignIn: (id) => import_electron.ipcRenderer.invoke(WELCOME_IPC.cancel, id),
  copySignInLink: (id) => import_electron.ipcRenderer.invoke(WELCOME_IPC.copyLink, id),
  onAccountState: (listener) => {
    const receive = (_event, state) => {
      listener(state);
    };
    import_electron.ipcRenderer.on(WELCOME_IPC.state, receive);
    return () => {
      import_electron.ipcRenderer.removeListener(WELCOME_IPC.state, receive);
    };
  },
  saveApiKey: (value) => import_electron.ipcRenderer.invoke(WELCOME_IPC.saveApiKey, value),
  skip: () => import_electron.ipcRenderer.invoke(WELCOME_IPC.skip)
};
import_electron.contextBridge.exposeInMainWorld("dshWelcome", api);
